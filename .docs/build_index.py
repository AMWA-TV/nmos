ROOT = Path(__file__).resolve().parent.parent
# Kept separate from the checked-in `docs/` (which contains hand-authored
# pages like FAQ.md, Introduction.md) so we never overwrite user content.
DOCS = ROOT / "build" / "docs"
SPECS_DIR = DOCS / "specs"

# The published NMOS index is a single JSON array. It contains the correct
# name/status/releases/default_branch data and is generated by the existing
# specs.amwa.tv rendering pipeline.
SPEC_SOURCE = os.environ.get(
    "NMOS_SPEC_SOURCE",
    "https://specs.amwa.tv/nmos/specs.json",
)

# Ordering + display names for the document-type facet. Anything not matched
# here falls into "Other" so nothing silently disappears from the index.
# These entries are maintained in the local NMOS list but the legacy published
# metadata still marks the control feature-set register as hidden. The Zensical
# index is the migration target, so explicitly include it here.
FORCE_ZENSICAL_INCLUDE = {"NMOS-CONTROL-FEATURE-SETS"}


TYPE_ORDER: list[tuple[str, str, str]] = [
    (
        "IS",
        "NMOS Interface Specifications (IS)",
        "APIs defined with RAML, JSON Schema and normative text.",
    ),
    (
        "MS",
        "NMOS Data Model Specifications (MS)",
        "Models for the resources used in NMOS APIs.",
    ),
    ("BCP", "NMOS Best Common Practices (BCP)", "Best practice for use of NMOS APIs."),
    (
        "INFO",
        "NMOS Informative Documents (INFO)",
        "Implementation guides and background information.",
    ),
    (
        "NMOS",
        "NMOS Registers & Feature Sets",
        "Parameter registers and control feature sets.",
    ),
]


@dataclass
class Spec:
    slug: str
    title: str = ""
    repo_name: str = ""
    repo_url: str = ""
    status: str = ""
    url: str = ""
    releases: list[str] = field(default_factory=list)
    default_branch: str = ""
    show_in_index: bool = True
    themes: list[str] = field(default_factory=list)
    intro: dict[str, list[str]] = field(default_factory=dict)

    @property
    def type(self) -> str:
        # Slugs look like IS-04, BCP-003-01, NMOS-PARAMETER-REGISTERS, ...
        head = self.slug.split("-", 1)[0].upper()
        if head in {"IS", "MS", "BCP", "INFO"}:
            return head
        if head == "NMOS":
            return "NMOS"
        return "OTHER"

    @property
    def link(self) -> str:
        return f"specs/{self.slug}.md"


def load_yaml(path: Path):
    with path.open("r", encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def fetch_spec_metadata() -> dict[str, dict]:
    """Fetch and index the published specs.json metadata."""
    if requests is None:
        return {}
    url = SPEC_SOURCE.format(slug="nmos", slug_lower="nmos")
    try:
        resp = requests.get(url, timeout=30)
        if resp.status_code != 200:
            print(f"  warn: HTTP {resp.status_code} from {url}", file=sys.stderr)
            return {}
        try:
            data = resp.json()
        except json.JSONDecodeError:
            data = yaml.safe_load(resp.text) or []
        if not isinstance(data, list):
            print(f"  warn: expected a JSON array from {url}", file=sys.stderr)
            return {}
        return {
            str(item.get("amwa_id", "")).upper(): item
            for item in data
            if isinstance(item, dict) and item.get("amwa_id")
        }
    except Exception as exc:  # noqa: BLE001 -- best effort
        print(f"  warn: could not fetch {url}: {exc}", file=sys.stderr)
        return {}


def fetch_increment_repositories() -> dict[str, dict[str, str]]:
    """Return Increment repositories so the NMOS index can host global search."""
    if requests is None:
        return {}
    url = "https://raw.githubusercontent.com/AMWA-TV/in-index/main/index.yml"
    try:
        response = requests.get(url, timeout=15)
        response.raise_for_status()
        data = yaml.safe_load(response.text) or {}
    except Exception as exc:  # noqa: BLE001 -- best-effort supplementary source
        print(f"  warn: could not fetch Increment index: {exc}", file=sys.stderr)
        return {}

    repositories: dict[str, dict[str, str]] = {}
    for document in data.get("documents", []) or []:
        repository = str(document.get("repo", "")).split("/", 1)[-1]
        if repository:
            repositories[repository] = {
                "collection": "AMWA Increments",
                "title": str(document.get("title", repository)),
            }
    return repositories


def fetch_global_manifest(repository: str) -> list[dict]:
    if requests is None:
        return []

    # Versioned repositories publish their current manifest below latest/;
    # fixed-version repositories may publish it at the unversioned root.
    urls = (
        f"https://specs.amwa.tv/new/{repository}/latest/global-search.json",
        f"https://specs.amwa.tv/new/{repository}/global-search.json",
    )
    for url in urls:
        try:
            response = requests.get(url, timeout=10)
            response.raise_for_status()
            data = response.json()
        except Exception:
            continue
        documents = data.get("documents", []) if isinstance(data, dict) else []
        return [document for document in documents if isinstance(document, dict)]
    return []


def build_global_search(specs: dict[str, Spec]) -> dict:
    """Merge per-repository manifests into the central static search index."""
    if os.environ.get("AMWA_GLOBAL_SEARCH", "1") == "0":
        return {"version": 1, "documents": []}

    repositories = {
        spec.repo_name: {"collection": "NMOS", "title": spec.title}
        for spec in specs.values()
        if spec.repo_name
    }
    repositories.update(fetch_increment_repositories())

    documents: list[dict] = []
    with ThreadPoolExecutor(max_workers=12) as executor:
        futures = {
            executor.submit(fetch_global_manifest, repository): repository
            for repository in repositories
        }
        for future in as_completed(futures):
            repository = futures[future]
            collection = repositories[repository]["collection"]
            for document in future.result():
                if not document.get("url") or not document.get("text"):
                    continue
                document = dict(document)
                document["repository"] = repository
                document["collection"] = collection
                documents.append(document)

    unique = {document["url"]: document for document in documents}
    return {
        "version": 1,
        "documents": sorted(
            unique.values(),
            key=lambda document: (document.get("title", "").lower(), document["url"]),
        ),
    }


