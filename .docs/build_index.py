INTRO_HEADINGS = {
    "What does it do?": "what_does_it_do",
    "Why does it matter?": "why_does_it_matter",
    "How does it work?": "how_does_it_work",
}


def readme_intro(text: str) -> dict[str, list[str]]:
    """Extract the standard intro bullet lists from a repository README."""
    if "<!-- INTRO-START -->" in text:
        text = text.split("<!-- INTRO-START -->", 1)[1]
    if "<!-- INTRO-END -->" in text:
        text = text.split("<!-- INTRO-END -->", 1)[0]

    intro: dict[str, list[str]] = {}
    current: str | None = None
    for line in text.splitlines():
        heading = re.match(r"^#{2,3}\s+(.+?)\s*$", line)
        if heading:
            current = INTRO_HEADINGS.get(heading.group(1))
            if current:
                intro[current] = []
            continue
        bullet = re.match(r"^\s*-\s+(.+?)\s*$", line)
        if current and bullet:
            intro[current].append(bullet.group(1))

    return {key: values for key, values in intro.items() if values}


def fetch_spec_intro(repository: str, default_branch: str = "") -> dict[str, list[str]]:
    """Fetch intro metadata, falling back to the repository README."""
    if requests is None or not repository:
        return {}

    urls = (
        f"https://specs.amwa.tv/new/{repository}/latest/spec.json",
        f"https://specs.amwa.tv/new/{repository}/spec.json",
    )
    for url in urls:
        try:
            response = requests.get(url, timeout=10)
            response.raise_for_status()
            data = response.json()
        except Exception:
            continue
        intro = data.get("intro", {}) if isinstance(data, dict) else {}
        if isinstance(intro, dict):
            result = {
                str(key): [str(item) for item in values]
                for key, values in intro.items()
                if isinstance(values, list) and values
            }
            if result:
                return result

    branches = list(dict.fromkeys(filter(None, (default_branch, "main", "master"))))
    for branch in branches:
        url = f"https://raw.githubusercontent.com/AMWA-TV/{repository}/{branch}/README.md"
        try:
            response = requests.get(url, timeout=10)
            response.raise_for_status()
        except Exception:
            continue
        intro = readme_intro(response.text)
        if intro:
            return intro
    return {}


def populate_spec_intros(specs: dict[str, Spec]) -> None:
    with ThreadPoolExecutor(max_workers=12) as executor:
        futures = {
            executor.submit(fetch_spec_intro, spec.repo_name, spec.default_branch): spec
            for spec in specs.values()
            if spec.repo_name
        }
        for future in as_completed(futures):
            intro = future.result()
            if intro:
                futures[future].intro = intro


def public_spec_url(slug: str, metadata_url: str = "") -> str:
    """Use the beta Zensical/Mike path for links from the NMOS index."""
    url = metadata_url or f"https://specs.amwa.tv/{slug.lower()}"
    # Beta-only routing: remove this conversion and use `url` directly when
    # the Zensical/Mike sites move back from `/new/` to the canonical paths.
    legacy_root = "https://specs.amwa.tv/"
    new_root = "https://specs.amwa.tv/new/"
    if url.startswith(legacy_root) and not url.startswith(new_root):
        return new_root + url[len(legacy_root):].lstrip("/")
    return url


def build_specs(spec_slugs: Iterable[str], themes: list[dict]) -> dict[str, Spec]:
    # Reverse lookup: slug -> [theme id, ...] preserving themes.yml order.
    slug_to_themes: dict[str, list[str]] = {}
    for theme in themes:
        for member in theme.get("members", []) or []:
            slug_to_themes.setdefault(member, []).append(theme["id"])

    metadata = fetch_spec_metadata()
    specs: dict[str, Spec] = {}
    for slug in spec_slugs:
        meta = metadata.get(slug.upper(), {})
        # Keep the local list as the allow-list, but respect the published
        # index's visibility flag for suite/template entries.
        if (
            meta
            and not bool(meta.get("show_in_index", True))
            and slug.upper() not in FORCE_ZENSICAL_INCLUDE
        ):
            continue
        # `name` is the human-friendly title in specs.json; `title` remains
        # supported for compatibility with alternate metadata sources.
        title = meta.get("name") or meta.get("title") or slug
        releases = meta.get("releases") or []
        # specs.json uses either a single string or a list depending on the
        # spec. Normalize both forms before rendering.
        if isinstance(releases, str):
            releases = [releases]
        elif not isinstance(releases, list):
            releases = []
        metadata_themes = meta.get("themes")
        themes_for_spec = (
            [str(theme) for theme in metadata_themes]
            if isinstance(metadata_themes, list)
            else slug_to_themes.get(slug, [])
        )
        specs[slug] = Spec(
            slug=slug,
            title=title,
            repo_name=meta.get("repo_name") or slug.lower(),
            repo_url=meta.get("repo_url") or f"https://github.com/AMWA-TV/{slug.lower()}",
            status=meta.get("status") or "",
            url=public_spec_url(slug, str(meta.get("url") or "")),
            releases=[str(release) for release in releases],
            default_branch=meta.get("default_branch") or "",
            show_in_index=bool(meta.get("show_in_index", True)),
            themes=themes_for_spec,
            intro={
                str(key): [str(item) for item in values]
                for key, values in (meta.get("intro", {}) or {}).items()
                if isinstance(values, list) and values
            },
        )
    return specs


