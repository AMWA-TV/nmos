def _sort_key(slug: str) -> tuple:
    """Natural-ish sort so IS-04 comes before IS-10 and BCP-002-01 before -02."""
    parts = re.split(r"[-_]", slug)
    return tuple((0, int(p)) if p.isdigit() else (1, p) for p in parts)


def spec_tooltip_sections(spec: Spec) -> list[tuple[str, list[str]]]:
    labels = (
        ("What does it do?", "what_does_it_do"),
        ("Why does it matter?", "why_does_it_matter"),
        ("How does it work?", "how_does_it_work"),
    )
    sections = []
    for heading, key in labels:
        bullets = []
        for value in spec.intro.get(key, []):
            cleaned = plain_text(str(value).strip())
            if cleaned:
                bullets.append(cleaned)
        if bullets:
            sections.append((heading, bullets))
    return sections


def spec_tooltip_text(spec: Spec, sections: list[tuple[str, list[str]]]) -> str:
    lines = [spec.title]
    for heading, bullets in sections:
        lines.extend(["", heading])
        lines.extend(f"• {bullet}" for bullet in bullets)
    return "\n".join(lines)


def plain_text(value: str) -> str:
    """Remove Markdown syntax before rendering the popup or an HTML attribute."""
    value = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", value)
    value = re.sub(r"``([^`]+)``", r"\1", value)
    return re.sub(r"`([^`]+)`", r"\1", value)


def spec_tooltip_html(spec: Spec, sections: list[tuple[str, list[str]]]) -> str:
    def safe(value: str) -> str:
        # A pipe can otherwise be interpreted as a Markdown table delimiter.
        return html.escape(value).replace("|", "&#124;")

    parts = [f'<span class="in-index-tooltip-title">{safe(spec.title)}</span>']
    for heading, bullets in sections:
        parts.append(
            f'<span class="in-index-tooltip-heading">{safe(heading)}</span>'
        )
        parts.extend(
            f'<span class="in-index-tooltip-item">• {safe(bullet)}</span>'
            for bullet in bullets
        )
    return "".join(parts)


def spec_link(spec: Spec) -> str:
    href = html.escape(spec.url, quote=True)
    label = html.escape(spec.slug)
    sections = spec_tooltip_sections(spec)
    if not sections:
        return f'<a href="{href}">{label}</a>'

    tooltip_text = html.escape(
        plain_text(spec_tooltip_text(spec, sections)).replace("\n", " | "),
        quote=True,
    ).replace("|", "&#124;")
    tooltip_markup = spec_tooltip_html(spec, sections)
    return (
        '<span class="in-index-entry">'
        f'<a href="{href}" aria-label="{tooltip_text}">{label}</a>'
        f'<span class="in-index-tooltip" role="tooltip">{tooltip_markup}</span>'
        "</span>"
    )


def render_spec_stub(spec: Spec, themes_by_id: dict[str, dict]) -> str:
    theme_names = [themes_by_id[t]["name"] for t in spec.themes if t in themes_by_id]
    # Tags let the Material `tags` plugin (and search) filter by type+theme.
    tags = [spec.type] + spec.themes
    front_matter = [
        "---",
        f"title: {spec.title}",
        "tags:",
        *[f"  - {t}" for t in tags],
        "---",
        "",
    ]
    releases_md = release_links(spec) if spec.releases else "_none published_"
    body = [
        f"# {spec.slug} &mdash; {spec.title}",
        "",
        f"- **Document type:** {spec.type}",
        f"- **Status:** {spec.status or '_unknown_'}",
        f"- **Themes:** {', '.join(theme_names) if theme_names else '_none_'}",
        f"- **Canonical URL:** <{spec.url}>",
        f"- **Repository:** <{spec.repo_url}>",
        f"- **Default branch:** `{spec.default_branch or 'unknown'}`",
        f"- **Releases:** {releases_md}",
        "",
    ]
    return "\n".join(front_matter + body)


def render_index() -> str:
    return (
        "# Networked Media Open Specifications\n\n"
        "The tables on the following pages list the current NMOS "
        "specifications, best practices and informative documents. "
        "Use the search box or the tag index to filter by document "
        "type or theme.\n\n"
        "- [By theme](by-theme.md) &mdash; grouped by subject area\n"
        "- [By type](by-type.md) &mdash; grouped by document type\n"
        "- [Tags](tags.md) &mdash; filter by any type or theme\n"
        "- [Global AMWA documentation search](global-search.md) &mdash; search across repositories\n"
    )


def release_links(spec: Spec) -> str:
    """Render the same release links as the legacy NMOS index."""
    if not spec.releases:
        return "&mdash;"
    return "<br>".join(
        f"[{release}]({spec.url.rstrip('/')}/{release})"
        f" [↓]({spec.repo_url}/releases/tag/{release})"
        for release in spec.releases
    )


def release_html(spec: Spec) -> str:
    if not spec.releases:
        return "&mdash;"
    return "<br>".join(
        f'<a href="{html.escape(spec.url.rstrip("/") + "/" + release, quote=True)}">'
        f"{html.escape(release)}</a> "
        f'<a href="{html.escape(spec.repo_url + "/releases/tag/" + release, quote=True)}">'
        "↓</a>"
        for release in spec.releases
    )


def render_spec_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    lines = [
        '<table class="in-index-table">',
        "<thead>",
        "<tr>" + "".join(f"<th>{html.escape(header)}</th>" for header in headers) + "</tr>",
        "</thead>",
        "<tbody>",
    ]
    for row in rows:
        lines.append("<tr>")
        lines.extend(f"<td>{cell}</td>" for cell in row)
        lines.append("</tr>")
    lines.extend(["</tbody>", "</table>"])
    return lines


def branch_html(spec: Spec) -> str:
    return (
        f"<code>{html.escape(spec.default_branch)}</code>"
        if spec.default_branch
        else "&mdash;"
    )


def has_release_column(entries: Iterable[Spec]) -> bool:
    """Return whether a table section contains any versioned specification."""
    return any(spec.releases for spec in entries)


def render_by_theme(specs: dict[str, Spec], themes: list[dict]) -> str:
    lines = ["# Specifications by theme", ""]
    for theme in themes:
        members = sorted(
            (m for m in (theme.get("members") or []) if m in specs),
            key=_sort_key,
        )
        if not members:
            continue
        lines.append(f"## {theme['name']}")
        lines.append("")
        description = theme.get("description")
        if description:
            lines.append(description)
            lines.append("")
        entries = [specs[slug] for slug in members]
        include_releases = has_release_column(entries)
        rows = []
        for spec in entries:
            row = [
                spec_link(spec),
                html.escape(spec.title),
                html.escape(spec.type),
                html.escape(spec.status) if spec.status else "&mdash;",
                branch_html(spec),
            ]
            if include_releases:
                row.append(release_html(spec))
            rows.append(row)
        headers = ["Spec", "Title", "Type", "Status", "Default branch"]
        if include_releases:
            headers.append("Release(s)")
        lines.extend(render_spec_table(headers, rows))
        lines.append("")
    return "\n".join(lines)


def render_by_type(specs: dict[str, Spec]) -> str:
    buckets: dict[str, list[Spec]] = {}
    for spec in specs.values():
        buckets.setdefault(spec.type, []).append(spec)

    lines = ["# Specifications by type", ""]
    seen: set[str] = set()
    for key, heading, blurb in TYPE_ORDER:
        entries = sorted(buckets.get(key, []), key=lambda s: _sort_key(s.slug))
        if not entries:
            continue
        seen.add(key)
        lines.append(f"## {heading}")
        lines.append("")
        lines.append(blurb)
        lines.append("")
        include_releases = has_release_column(entries)
        rows = []
        for spec in entries:
            row = [
                spec_link(spec),
                html.escape(spec.title),
                html.escape(", ".join(spec.themes)) if spec.themes else "&mdash;",
                html.escape(spec.status) if spec.status else "&mdash;",
                branch_html(spec),
            ]
            if include_releases:
                row.append(release_html(spec))
            rows.append(row)
        headers = ["Spec", "Title", "Themes", "Status", "Default branch"]
        if include_releases:
            headers.append("Release(s)")
        lines.extend(render_spec_table(headers, rows))
        lines.append("")

    # Anything unclassified.
    other = sorted(
        (s for k, group in buckets.items() if k not in seen for s in group),
        key=lambda s: _sort_key(s.slug),
    )
    if other:
        lines.append("## Other")
        lines.append("")
        include_releases = has_release_column(other)
        rows = []
        for spec in other:
            row = [
                spec_link(spec),
                html.escape(spec.title),
                html.escape(", ".join(spec.themes)) if spec.themes else "&mdash;",
                html.escape(spec.status) if spec.status else "&mdash;",
                branch_html(spec),
            ]
            if include_releases:
                row.append(release_html(spec))
            rows.append(row)
        headers = ["Spec", "Title", "Themes", "Status", "Default branch"]
        if include_releases:
            headers.append("Release(s)")
        lines.extend(render_spec_table(headers, rows))
        lines.append("")
    return "\n".join(lines)


def tag_anchor(tag: str) -> str:
    return "tag-" + re.sub(r"[^a-z0-9]+", "-", tag.lower()).strip("-")


def render_tags_page(specs: dict[str, Spec]) -> str:
    """Render a tag cloud and explicit tag sections.

    Zensical currently lists the Material `tags` plugin as a compatibility
    backlog item, so relying on its automatic tags index leaves `tags.md`
    empty. Generate the view directly while retaining tags in front matter
    for search and future native tag support.
    """
    grouped: dict[str, list[Spec]] = {}
    for spec in specs.values():
        for tag in [spec.type, *spec.themes]:
            grouped.setdefault(tag, []).append(spec)

    tags = sorted(grouped)
    if not tags:
        return "# Tags\n\n_No tags available._\n"

    largest = max(len(grouped[tag]) for tag in tags)
    cloud = [
        "# Tags",
        "",
        "Filter the specification index by document type or theme. Select a tag to see its matching specifications.",
        "",
        '<div class="tag-cloud" markdown>',
    ]
    for tag in tags:
        # Scale the font modestly according to the number of matching specs.
        size = 0.9 + (0.5 * len(grouped[tag]) / largest)
        label = html.escape(tag)
        cloud.append(
            f'<a href="#{tag_anchor(tag)}" style="font-size: {size:.2f}rem">'
            f"{label} <small>({len(grouped[tag])})</small></a>"
        )
    cloud.extend(["</div>", ""])

    for tag in tags:
        cloud.extend([
            f"## {tag} {{ #{tag_anchor(tag)} }}",
            "",
        ])
        for spec in sorted(grouped[tag], key=lambda item: _sort_key(item.slug)):
            cloud.append(f"- {spec_link(spec)} &mdash; {html.escape(spec.title)}")
        cloud.append("")

    return "\n".join(cloud)


